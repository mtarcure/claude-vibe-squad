#!/usr/bin/env bash
# Generate the human-readable model-lead roster from the canonical TSV map.

set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
SOURCE_FILE="${ROSTER_SOURCE_FILE:-${ROOT}/shared/specialist-runtime-map.tsv}"
OUTPUT_FILE="${ROSTER_OUTPUT_FILE:-${ROOT}/model-lanes/ROSTER.md}"
MODE="${1:---write}"

usage() {
    cat <<'EOF'
Usage: bin/gen-roster.sh [--write|--check|--stdout]

  --write   Atomically regenerate model-lanes/ROSTER.md (default).
  --check   Fail and print a unified diff when the roster has drifted.
  --stdout  Print the generated roster without writing it.

ROSTER_SOURCE_FILE and ROSTER_OUTPUT_FILE may override the paths for hermetic tests.
EOF
}

case "$MODE" in
    --write|--check|--stdout) ;;
    -h|--help)
        usage
        exit 0
        ;;
    *)
        usage >&2
        exit 64
        ;;
esac

if [[ ! -f "$SOURCE_FILE" ]]; then
    echo "roster generator: source not found: $SOURCE_FILE" >&2
    exit 66
fi

generate() {
    awk -F '\t' '
        BEGIN {
            expected = "specialist\tsource_namespace\tcapability_class\tsafety_level\tsafety_tags\ttool_profile\tprimary_lane\tprimary_profile\tbackup_lane\tbackup_profile\tescalate_lane\tescalate_profile\tescalation_policy\treview_lane\treview_profile\tanti_affinity\tthroughput_lane\tthroughput_profile\tthroughput_policy\tfailover_policy\toperator_gate\theightened_risk\trequires_approval\trequired_tools\tpreferred_tools\tnotes\ttags\tversion\toperator_model_consult"
        }

        NR == 1 {
            if ($0 != expected || NF != 29) {
                print "roster generator: unexpected TSV header" > "/dev/stderr"
                failed = 1
            }
            next
        }

        {
            if (NF != 29) {
                printf "roster generator: line %d has %d fields; expected 29\n", NR, NF > "/dev/stderr"
                failed = 1
                next
            }
            if ($7 !~ /^(codex|claude|gemini|kimi)$/) {
                printf "roster generator: line %d has invalid primary_lane: %s\n", NR, $7 > "/dev/stderr"
                failed = 1
                next
            }
            if ($14 !~ /^(codex|claude|gemini|kimi|none)$/) {
                printf "roster generator: line %d has invalid review_lane: %s\n", NR, $14 > "/dev/stderr"
                failed = 1
                next
            }
            specialist[++count] = $1
            source[count] = $2
            safety[count] = $4
            primary[count] = $7
            review[count] = $14
        }

        END {
            if (failed) {
                exit 65
            }

            print "# Model Lead Roster"
            print ""
            print "<!-- Generated by bin/gen-roster.sh; do not edit. -->"
            print "Generated from `shared/specialist-runtime-map.tsv`. The TSV is the routing source of truth."
            print ""

            lane_order[1] = "codex"
            lane_order[2] = "claude"
            lane_order[3] = "gemini"
            lane_order[4] = "kimi"
            lane_heading["codex"] = "GPT/Codex"
            lane_heading["claude"] = "Claude"
            lane_heading["gemini"] = "Gemini"
            lane_heading["kimi"] = "Kimi"

            for (lane_index = 1; lane_index <= 4; lane_index++) {
                lane = lane_order[lane_index]
                print "## " lane_heading[lane]
                print ""
                for (row = 1; row <= count; row++) {
                    if (primary[row] != lane) {
                        continue
                    }
                    review_display = review[row] == "codex" ? "gpt-codex" : review[row]
                    printf "- `%s` (source: `%s`, review: `%s`, safety: `%s`)\n", specialist[row], source[row], review_display, safety[row]
                }
                if (lane_index < 4) {
                    print ""
                }
            }
        }
    ' "$SOURCE_FILE"
}

case "$MODE" in
    --stdout)
        generate
        ;;
    --check)
        CHECK_FILE="$(mktemp "${TMPDIR:-/tmp}/vibe-roster-check.XXXXXX")"
        trap 'rm -f -- "$CHECK_FILE"' EXIT
        generate > "$CHECK_FILE"
        if [[ ! -f "$OUTPUT_FILE" ]] || ! cmp -s "$CHECK_FILE" "$OUTPUT_FILE"; then
            echo "roster drift: $OUTPUT_FILE does not match $SOURCE_FILE" >&2
            diff -u "$OUTPUT_FILE" "$CHECK_FILE" >&2 || true
            exit 1
        fi
        echo "PASS: model-lanes/ROSTER.md matches shared/specialist-runtime-map.tsv"
        ;;
    --write)
        OUTPUT_DIR="$(dirname -- "$OUTPUT_FILE")"
        if [[ ! -d "$OUTPUT_DIR" ]]; then
            echo "roster generator: output directory not found: $OUTPUT_DIR" >&2
            exit 66
        fi
        WRITE_FILE="$(mktemp "${OUTPUT_FILE}.tmp.XXXXXX")"
        trap 'rm -f -- "$WRITE_FILE"' EXIT
        generate > "$WRITE_FILE"
        chmod 0644 "$WRITE_FILE"
        sync
        mv -f -- "$WRITE_FILE" "$OUTPUT_FILE"
        trap - EXIT
        echo "generated $OUTPUT_FILE from $SOURCE_FILE"
        ;;
esac
